/* =====================================================
   VARIABEL
===================================================== */

let currentStory = 0;

let speech = null;

let musicStarted = false;


/* =====================================================
   ELEMENT HTML
===================================================== */

const storyImage = document.getElementById("storyImage");

const storyTitle = document.getElementById("storyTitle");

const storyDescription = document.getElementById("storyDescription");

const moralText = document.getElementById("moralText");

const pageCounter = document.getElementById("pageCounter");

const dotsContainer = document.getElementById("dots");

const backgroundMusic = document.getElementById("backgroundMusic");

const musicButton = document.getElementById("musicButton");


/* =====================================================
   PENGATURAN MUSIK
===================================================== */

backgroundMusic.volume = 0.20;


/* =====================================================
   TAMPILKAN CERITA
===================================================== */

function showStory() {

    const story = stories[currentStory];


    storyImage.src = story.image;

    storyImage.alt = story.title;


    storyTitle.textContent = story.title;


    storyDescription.textContent = story.description;


    moralText.textContent = story.moral;


    pageCounter.textContent =
        `Halaman ${currentStory + 1} dari ${stories.length}`;


    createDots();
}


/* =====================================================
   MEMBUAT DOT
===================================================== */

function createDots() {

    dotsContainer.innerHTML = "";


    stories.forEach((story, index) => {

        const dot = document.createElement("span");

        dot.classList.add("dot");


        if (index === currentStory) {
            dot.classList.add("active");
        }


        dot.title = story.title;


        dot.onclick = function () {

            stopStory();

            currentStory = index;

            showStory();

        };


        dotsContainer.appendChild(dot);

    });

}


/* =====================================================
   MENCARI SUARA INDONESIA
===================================================== */

function getIndonesianVoice() {

    const voices = speechSynthesis.getVoices();


    let voice = voices.find(
        v => v.lang === "id-ID"
    );


    if (!voice) {

        voice = voices.find(
            v => v.lang.toLowerCase().startsWith("id")
        );

    }


    return voice;
}


/* =====================================================
   PUTAR CERITA
===================================================== */

function speakStory() {

    if (!("speechSynthesis" in window)) {

        alert(
            "Browser kamu tidak mendukung fitur suara."
        );

        return;

    }


    speechSynthesis.cancel();


    const story = stories[currentStory];


    const text =
        `${story.title}. ` +
        `${story.description}. ` +
        `Pesan moral. ${story.moral}`;


    speech = new SpeechSynthesisUtterance(text);


    speech.lang = "id-ID";

    speech.rate = 0.85;

    speech.pitch = 1;

    speech.volume = 1;


    const voice = getIndonesianVoice();


    if (voice) {
        speech.voice = voice;
    }


    speechSynthesis.speak(speech);

}


/* =====================================================
   JEDA SUARA
===================================================== */

function pauseStory() {

    if ("speechSynthesis" in window) {

        speechSynthesis.pause();

    }

}


/* =====================================================
   LANJUTKAN SUARA
===================================================== */

function resumeStory() {

    if ("speechSynthesis" in window) {

        speechSynthesis.resume();

    }

}


/* =====================================================
   BERHENTI SUARA
===================================================== */

function stopStory() {

    if ("speechSynthesis" in window) {

        speechSynthesis.cancel();

    }

}


/* =====================================================
   CERITA BERIKUTNYA
===================================================== */

function nextStory() {

    stopStory();


    if (currentStory < stories.length - 1) {

        currentStory++;

    } else {

        currentStory = 0;

    }


    showStory();


    setTimeout(() => {

        speakStory();

    }, 500);

}


/* =====================================================
   CERITA SEBELUMNYA
===================================================== */

function previousStory() {

    stopStory();


    if (currentStory > 0) {

        currentStory--;

    } else {

        currentStory = stories.length - 1;

    }


    showStory();


    setTimeout(() => {

        speakStory();

    }, 500);

}


/* =====================================================
   KEMBALI KE CERITA PERTAMA
===================================================== */

function backToStart() {

    stopStory();


    currentStory = 0;


    showStory();


    setTimeout(() => {

        speakStory();

    }, 500);

}


/* =====================================================
   MUSIK BACKGROUND
===================================================== */

function toggleMusic() {

    if (backgroundMusic.paused) {

        backgroundMusic.play()

            .then(() => {

                musicStarted = true;

                musicButton.textContent =
                    "🎵 Musik ON";

                musicButton.classList.add("active");

            })

            .catch((error) => {

                console.log(
                    "Musik gagal diputar:",
                    error
                );


                alert(
                    "Musik belum bisa diputar. Pastikan file musik-dongeng.mp3 ada di folder audio."
                );

            });

    } else {

        backgroundMusic.pause();


        musicButton.textContent =
            "🎵 Musik OFF";


        musicButton.classList.remove("active");

    }

}


/* =====================================================
   OTOMATIS MENCOBA MEMULAI MUSIK
===================================================== */

document.addEventListener(
    "click",
    function startMusicAfterClick() {

        if (
            !musicStarted &&
            backgroundMusic.paused
        ) {

            backgroundMusic.play()

                .then(() => {

                    musicStarted = true;

                    musicButton.textContent =
                        "🎵 Musik ON";

                    musicButton.classList.add(
                        "active"
                    );

                })

                .catch(() => {

                    // Browser menolak autoplay.
                    // User tinggal klik tombol Musik.

                });

        }

    },
    {
        once: true
    }
);


